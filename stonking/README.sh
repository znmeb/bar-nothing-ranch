 # How to build and run
 
1. You will need to set the administrative user password. Do

    export ADMIN_PASSWD="Y0ur&pA550RD$G035,h3r3"

2. Build the image: `./1-podman-build.sh`.

3. Create and run the container: `./2-podman-run.sh`.

To get a command line in the container, type `./podman-exec.sh`.
